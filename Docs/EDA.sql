-- Date Exploration.
-- find the date of first and last order.
-- how many years of sales are avaiable.alter.
SELECT 
    MIN(order_date) AS first_order,
    MAX(order_date) AS last_order,
    TIMESTAMPDIFF(YEAR,
        MIN(order_date),
        MAX(order_date)) AS order_range_month
FROM
    fact_sales
WHERE
    order_date IS NOT NULL
        AND CAST(order_date AS CHAR) != '0000-00-00';

-- find the youngest and oldest customer.
SELECT 
    MIN(birthdate) AS youngest,
    TIMESTAMPDIFF(YEAR,
        MIN(birthdate),
        CURDATE()) AS oldest_age,
    TIMESTAMPDIFF(YEAR,
        MAX(birthdate),
        CURDATE()) AS youngest_age,
    MAX(birthdate) AS oldest
FROM
    dim_customers
WHERE
    birthdate IS NOT NULL
        AND CAST(birthdate AS CHAR) != '0000-00-00';

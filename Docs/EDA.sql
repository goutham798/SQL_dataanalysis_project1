-- 5.Magnitude Analysis.
-- Find total customers by countries.
select country,count( distinct customer_key) as total_customers from dim_customers
group by country;

-- Find total customers by gender
select gender,count(distinct customer_number) as total_customers from dim_customers
group by gender;

-- Find total products by category.
select category,count(product_key) as total_products from dim_products
group by  category;

-- What is the average costs in each category?
select category,round(avg(cost),2) as avg_cost from dim_products
group by category;

-- What is the total revenue generated for each category?
select p.category,
sum(f.sales_amount) as total_revenue
from dim_products p
left join fact_sales f
on p.product_key = f.product_key
group by 1
having total_revenue is not null
order by 2 desc;

-- Find total revenue is generated by each customer.
select customer_key as customers,sum(sales_amount) as total_revenue from fact_sales
group by 1
order by 2 desc;

-- What is the distribution of sold items across countries?;
SELECT 
    c.country,
    SUM(f.quantity) AS total_quantity
FROM fact_sales f
LEFT JOIN dim_customers c ON f.customer_key = c.customer_key
GROUP BY 1
ORDER BY 2 DESC;

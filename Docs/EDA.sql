-- Rank Analysis.
-- Which 5 products generate the highest evenue?
select *
from(
select p.product_name,
sum(f.sales_amount) as total_revenue,
row_number() over(order by sum(f.sales_amount) desc) as rank_products
from dim_products p
left join fact_sales f
on p.product_key = f.product_key
group by 1
having total_revenue is not null
order by 2 desc) t
where rank_products <=5;


-- Which 5 products generate the worst evenue?
select p.product_name,
sum(f.sales_amount) as total_revenue,
row_number() over(order by sum(f.sales_amount)) as rank_products
from dim_products p
left join fact_sales f
on p.product_key = f.product_key
group by 1
having total_revenue is not null
order by 2 asc
limit 5;

-- The 3 customers with the fewest orders placed
SELECT  
    f.customer_key,
    c.first_name,
    c.last_name,
    COUNT(DISTINCT order_number) AS total_orders
FROM fact_sales f
LEFT JOIN dim_customers c ON c.customer_key = f.customer_key
GROUP BY f.customer_key, c.first_name, c.last_name
ORDER BY total_orders asc
limit 3;
